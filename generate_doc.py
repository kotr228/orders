# ─── helpers for tables / figures ────────────────────────────────────────────
def fill_cell(cell, text, bold=False, italic=False,
              align=WD_ALIGN_PARAGRAPH.LEFT, size=12):
    p = cell.paragraphs[0]
    p.clear()
    p.alignment = align
    _set_spacing_15(p)
    run = p.add_run(text)
    set_font(run, bold=bold, italic=italic, size=size)

